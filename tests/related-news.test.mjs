import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source = fs.readFileSync(new URL('../app.js', import.meta.url), 'utf8');
const context = vm.createContext({btoa,document:{querySelector:()=>({}),querySelectorAll:()=>[]},crypto:{randomUUID:()=> 'test'}});
vm.runInContext(source.slice(0, source.indexOf('[\n  els.searchInput,')), context);
const payload = JSON.parse(fs.readFileSync(new URL('../data/overseas-news.json', import.meta.url)));
context.payload = payload;
const items = vm.runInContext('payload.articles.map(a => normalizeArticle(normalizeLegacyArticle(a, payload, "global")))', context);
const payments = items.filter(a=> /111/.test(a.title_original) && a.published_date.startsWith('2026-11-0'));
assert.equal(payments.length,5);
context.items=payments;
const groups=vm.runInContext('collapseRelatedNews(items)',context);
assert.equal(groups.length,1);
assert.equal(groups[0].related_articles.length,4);
assert.equal(groups[0].published_date,'2026-11-05T16:23:29.000Z');
context.earlier={...payments[0],published_date:'2026-10-18T07:00:00Z'};
context.different={...payments[0],url:'https://example.com/different',title_original:'اطلاق 300 مليون دولار لشركة هانوا في بسماية',title_ko:'한화에 3억 달러 지급'};
assert.equal(vm.runInContext('sameNewsEvent(items[0], earlier)',context),false);
assert.equal(vm.runInContext('sameNewsEvent(items[0], different)',context),false);
context.unrelated={...payments[0],url:'https://example.com/school',title_original:'افتتاح مدرسة في بسماية',title_ko:'비스마야 학교 개교',summary_ko:'학교 개교 행사'};
assert.equal(vm.runInContext('sameNewsEvent(items[0], unrelated)',context),false);
assert.ok(source.includes('<summary>관련기사 ('));
console.log('Related news: 5 payment reports → 1 card + 4 title links; date/amount/unrelated guards passed');
